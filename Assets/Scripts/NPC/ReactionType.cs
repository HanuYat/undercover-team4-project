/// <summary>
/// 검거 반응 유형 — 수갑 채널링 성공 순간 NPC가 보이는 반응. (GDD 6-1, #76)
/// 일반 시민은 전부 순응이고, 범인만 CriminalAssigner가 가중치 추첨으로 배정한다.
/// 거수자(무작위 반응, GDD 6-2)는 후속 돌발이벤트 이슈에서 이 타입을 재사용한다.
/// </summary>
public enum ReactionType
{
    Compliant, // 순응 — 반항 없이 즉시 연행 (기존 동작)
    Flee,      // 도주 — 뿌리치고 도망. 근접 제압 홀드 또는 테이저(후속)로만 잡힌다
    Resist,    // 저항 — 제자리에서 버팀. 제압 게이지를 깎아야 체포된다
}
