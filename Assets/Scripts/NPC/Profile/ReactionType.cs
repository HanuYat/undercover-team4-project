/// <summary>
/// 반응을 촉발한 행위 — 순응형 처리가 여기서 갈린다. (#400)
/// 스캔에는 순응형이 무반응이지만, 피격에는 도주·저항 중 하나로 반응한다.
/// </summary>
public enum ReactionTrigger
{
    Scan,   // 스캔당함 — 의심받는 행위. 순응형은 아무 반응도 하지 않는다
    Damage, // 플레이어에게 맞음(진압봉·E 제압 타격) — 순응형도 반응한다(도주·저항 랜덤, 1회 확정).
            // 폭발 같은 환경 피해는 트리거가 아니다 — 판정은 타격 경로가 직접 부른다
}

/// <summary>
/// 검거 반응 유형 — 스캔·피격당한 순간 NPC가 보이는 반응. (GDD 6-1, #76 → 트리거 변경 #400)
/// 일반 시민은 전부 순응이고, 범인만 CriminalAssigner가 가중치 추첨으로 배정한다.
/// 거수자(무작위 반응, GDD 6-2)는 후속 돌발이벤트 이슈에서 이 타입을 재사용한다.
/// </summary>
public enum ReactionType
{
    Compliant, // 순응 — 반항 없이 즉시 연행 (기존 동작)
    Flee,      // 도주 — 뿌리치고 도망. 근접 제압 홀드 또는 테이저(후속)로만 잡힌다
    Resist,    // 저항 — 제자리에서 버팀. 제압 게이지를 깎아야 체포된다
}
